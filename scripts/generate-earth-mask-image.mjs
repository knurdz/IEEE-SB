import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(projectRoot, 'public', 'earth_specular_2048.jpg');
const outputPath = path.join(projectRoot, 'lib', 'earth-mask-image.ts');

const WIDTH = 512;
const HEIGHT = 256;

const buffer = await sharp(sourcePath)
  .resize(WIDTH, HEIGHT, { fit: 'fill' })
  .grayscale()
  .png({ compressionLevel: 9 })
  .toBuffer();

const dataUrl = `data:image/png;base64,${buffer.toString('base64')}`;
const fileContents = `// Generated by scripts/generate-earth-mask-image.mjs
// Uses an inline data URL so the globe mask stays readable under file:// exports.
export const EARTH_MASK_IMAGE_WIDTH = ${WIDTH};
export const EARTH_MASK_IMAGE_HEIGHT = ${HEIGHT};
export const EARTH_MASK_DATA_URL = '${dataUrl}';
`;

writeFileSync(outputPath, fileContents);
console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
